        XCTAssertEqual(NounBankMark.computedInitials("Ace of Spades"), "AS")
        XCTAssertEqual(NounBankMark.computedInitials("OG kush"), "OK")
        XCTAssertEqual(NounBankMark.computedInitials("Glock 40"), "G4")
        XCTAssertEqual(NounBankMark.computedInitials("FN"), "FN")
    }

    func testEveryStoredNounGetsACompactMark() {
        for category in NounBankCategory.allCases {
            for word in NounBankStore.words(for: category) {
                let mark = NounBankMark.identity(for: word, category: category)
                XCTAssertFalse(mark.initials.isEmpty, "\(category.rawValue) \(word)")
                XCTAssertLessThanOrEqual(mark.initials.count, 3, "\(category.rawValue) \(word) -> \(mark.initials)")
                XCTAssertEqual(mark.initials, mark.initials.uppercased())
            }
        }
    }

