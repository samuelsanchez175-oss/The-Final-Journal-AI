    func testSyrupMarksUseTheLiquidColor() {
        let purple = NounBankMark.identity(for: "lean", category: .syrups)
        let actavis = NounBankMark.identity(for: "Actavis", category: .syrups)
        let hiTech = NounBankMark.identity(for: "Hi-Tech", category: .syrups)
        let techPints = NounBankMark.identity(for: "tech pints", category: .syrups)
        let wock = NounBankMark.identity(for: "Wockhardt", category: .syrups)
        let betterWock = NounBankMark.identity(for: "Better Wock", category: .syrups)
        let sprite = NounBankMark.identity(for: "dirty sprite", category: .syrups)
        let green = NounBankMark.identity(for: "lean green", category: .syrups)
        let qualitest = NounBankMark.identity(for: "qualitest", category: .syrups)
        let robitussin = NounBankMark.identity(for: "robitussin", category: .syrups)
        let daiquiri = NounBankMark.identity(for: "codeine daiquiri", category: .syrups)

        XCTAssertEqual(purple.hex, 0x6B3FA0)
        XCTAssertEqual(actavis.hex, 0x6B3FA0)
        XCTAssertEqual(hiTech.initials, "HT")
        XCTAssertEqual(hiTech.hex, 0xC62828)
        XCTAssertEqual(techPints.hex, hiTech.hex)
        XCTAssertEqual(wock.initials, "WK")
        XCTAssertEqual(wock.hex, 0xC6B03A)
        XCTAssertEqual(betterWock.hex, wock.hex)
        XCTAssertNotEqual(wock.hex, purple.hex)
        XCTAssertEqual(sprite.initials, "DS")
        XCTAssertEqual(sprite.hex, 0x2E9B4A)
        XCTAssertEqual(green.initials, "LG")
        XCTAssertEqual(green.hex, 0x3D8B3A)
        XCTAssertEqual(qualitest.hex, 0xE0A825)
        XCTAssertEqual(robitussin.hex, 0xD4451D)
        XCTAssertEqual(daiquiri.initials, "DQ")
        XCTAssertEqual(daiquiri.hex, 0xD46A8A)
        XCTAssertNotEqual(hiTech.hex, wock.hex)
        XCTAssertNotEqual(sprite.hex, purple.hex)
    }

