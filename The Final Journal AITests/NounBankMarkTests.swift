final class NounBankMarkTests: XCTestCase {

    func testHennyAndHennessyShareHouseMark() {
        let henny = NounBankMark.identity(for: "Henny", category: .liquors)
        let hennessy = NounBankMark.identity(for: "Hennessy", category: .liquors)
        XCTAssertEqual(henny.initials, "HN")
        XCTAssertEqual(hennessy.initials, "HN")
        XCTAssertEqual(henny.hex, hennessy.hex)
        XCTAssertEqual(henny.family, "hennessy")
        XCTAssertEqual(hennessy.family, "hennessy")
        XCTAssertEqual(henny.glyph, .cognacBottle)
    }

    func testRemyFamilyAndDomFamilyKeepTheirOwnMarks() {
        let remy = NounBankMark.identity(for: "Rémy", category: .liquors)
        let remyMartin = NounBankMark.identity(for: "Rémy Martin", category: .liquors)
        XCTAssertEqual(remy.initials, "RM")
        XCTAssertEqual(remyMartin.initials, "RM")
        XCTAssertEqual(remy.hex, remyMartin.hex)

        let domP = NounBankMark.identity(for: "Dom P", category: .liquors)
        let domPerignon = NounBankMark.identity(for: "Dom Pérignon", category: .liquors)
        XCTAssertEqual(domP.initials, "DP")
        XCTAssertEqual(domPerignon.initials, "DP")
        XCTAssertEqual(domP.glyph, .champagneBottle)
    }

