    private static func isBareHouseAlias(_ word: String) -> Bool {
        let key = NounBankMark.normalize(word)
        if productIcons[key] != nil { return false }
        let tokens = key.split(separator: " ").map(String.init)
        if tokens.contains(where: { productTokens.contains($0) }) { return false }
        if tokens.contains(where: { $0.contains(where: \.isNumber) }) { return false }
        return true
    }

    private static func isAliasOfCanonical(_ slang: String, _ canon: String) -> Bool {
        let s = NounBankMark.normalize(slang)
        let c = NounBankMark.normalize(canon)
        if s == c { return true }
        if c.hasPrefix(s) { return true }
        let cTokens = c.split(separator: " ").map(String.init)
        let sTokens = s.split(separator: " ").map(String.init)
        if !sTokens.isEmpty, sTokens.allSatisfy({ t in cTokens.contains(where: { $0.hasPrefix(t) }) }) {
            return true
        }
        if cTokens.count >= 2 {
            let initials = cTokens.map { String($0.prefix(1)) }.joined()
            if s.replacingOccurrences(of: " ", with: "") == initials { return true }
        }
        let stem = String(s.replacingOccurrences(of: " ", with: "").prefix(4))
        let cJoin = c.replacingOccurrences(of: " ", with: "")
        if stem.count == 4, cJoin.hasPrefix(stem) { return true }
        return false
    }

    private static func preferredHouseAlias(_ aliases: [String], category: NounBankCategory) -> String {
        let norm: (String) -> String = { NounBankMark.normalize($0) }
        return aliases.min { a, b in
            let ac = canonical(for: a, category: category)
            let bc = canonical(for: b, category: category)
            let aSlang = ac.map { norm(a) != norm($0) } ?? false
            let bSlang = bc.map { norm(b) != norm($0) } ?? false
            if aSlang != bSlang { return aSlang && !bSlang }
            if a.count != b.count { return a.count < b.count }
            return false
        } ?? aliases[0]
    }

    static func makeItem(word: String, category: NounBankCategory, sortIndex: Int) -> NounBankItem {
        let mark = NounBankMark.identity(for: word, category: category)
        let canonical = Self.canonical(for: word, category: category)
        let label: String
        if let canonical, !word.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: .current)
            .elementsEqual(canonical.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: .current)) {
            label = "\(word) (\(canonical))"
        } else {
            label = word
        }
        return NounBankItem(
            insertWord: word,
            label: label,
            canonical: canonical,
            family: mark.family,
            hex: mark.hex,
            icon: iconName(for: word, family: mark.family, category: category),
            sortIndex: sortIndex
        )
    }

