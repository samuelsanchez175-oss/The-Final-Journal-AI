    /// Real name shown in parentheses on slang tiles. Nil means the chip already is the real name.
    static func canonical(for word: String, category: NounBankCategory) -> String? {
        let key = NounBankMark.normalize(word)
        if let mapped = slangCanonical[key] { return mapped }
        switch category {
        case .liquors:
            return liquorCanonical[key]
        case .syrups:
            return syrupCanonical[key]
        case .drugs:
            return drugCanonical[key]
        case .jewelry:
            return jewelryCanonical[key]
        case .brands, .clothing:
            return brandCanonical[key]
        case .guns:
            return gunCanonical[key]
        case .money:
            return moneyCanonical[key]
        case .cars, .boats, .aviation, .military:
            return carCanonical[key]
        case .woman:
            return womanCanonical[key]
        case .family, .friends, .animals, .insects, .food, .grills, .hair, .nails, .tattoos, .games, .events, .flowers, .lingerie, .toys, .twerk, .streets, .kingpin, .trapLife, .paranoia:
            return nil
        case .places:
            return placeCanonical[key]
        case .kill:
            return nil
        case .jewelers:
            return jewelerCanonical[key]
        case .producers:
            return producerCanonical[key]
        case .artists:
            return artistCanonical[key]
        case .opps:
            return oppCanonical[key]
        case .celebs, .characters, .nba, .nfl, .boxing, .sports, .wrestlers, .actors, .streamers:
            return nil
        case .substances, .religion, .feelings, .phrases, .wordplay, .looks:
            return nil
        case .apps:
            return appCanonical[key]
        }
    }

