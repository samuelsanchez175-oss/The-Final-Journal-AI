/// SF Symbol for a noun chip that has no photo.
/// A name this SDK cannot draw would leave the button blank, so every name here is one that resolves.
nonisolated enum NounBankSymbols {
    static func symbol(for word: String, category: NounBankCategory) -> String {
        let key = normalize(word)
        if let named = explicit[category]?[key] {
            return named
        }
        return hashedSymbol(for: key, category: category)
    }

    private static func hashedSymbol(for key: String, category: NounBankCategory) -> String {
        var deck = pool
        if let used = explicit[category]?.values {
            let open = pool.filter { !Set(used).contains($0) }
            if open.count >= 8 { deck = open }
        }
        let salt = stableIndex(category.rawValue, mod: deck.count)
        let index = (salt + stableIndex(key, mod: deck.count)) % deck.count
        return deck[index]
    }

    /// Same folding as `NounBankMark.normalize`: apostrophes drop, hyphens become spaces.
    private static func normalize(_ word: String) -> String {
        word.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: .current)
            .lowercased()
            .replacingOccurrences(of: "\u{2019}", with: "")
            .replacingOccurrences(of: "'", with: "")
            .replacingOccurrences(of: ".", with: "")
            .replacingOccurrences(of: "-", with: " ")
            .replacingOccurrences(of: "/", with: " ")
            .split(whereSeparator: \.isWhitespace)
            .joined(separator: " ")
    }

    private static func stableIndex(_ text: String, mod: Int) -> Int {
        var hash: UInt64 = 5381
        for byte in text.utf8 { hash = hash &* 33 &+ UInt64(byte) }
        return Int(hash % UInt64(max(mod, 1)))
    }

