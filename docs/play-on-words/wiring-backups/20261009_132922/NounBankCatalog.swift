    static func items(for category: NounBankCategory) -> [NounBankItem] {
        let words = collapseSpelledOutDuplicates(NounBankStore.words(for: category), category: category)
        let raw: [NounBankItem] = words.enumerated().map { index, word in
            makeItem(word: word, category: category, sortIndex: index)
        }
        var familyOrder: [String] = []
        for item in raw where !familyOrder.contains(item.family) {
            familyOrder.append(item.family)
        }
        let grouped = Dictionary(grouping: raw, by: \.family)
        return familyOrder.flatMap { family in
            (grouped[family] ?? []).sorted { $0.sortIndex < $1.sortIndex }
        }
    }

    /// One chip per thing: keep the lyric short form (`Dom P`, `Henny`) with the
    /// real name in parentheses, and drop the extra tile that is only that real name.
    /// Product chips (Louis pouch, Force 1) stay. Nested names keep the more complete
    /// lyric (`Ace of Spades` over `Ace`).
    static func collapseSpelledOutDuplicates(_ words: [String], category: NounBankCategory) -> [String] {
        let norm: (String) -> String = { NounBankMark.normalize($0) }
        var drop = Set<String>()
        for word in words {
            if productIcons[norm(word)] != nil { continue }
            guard let canon = canonical(for: word, category: category) else { continue }
            if norm(word) == norm(canon) { continue }
            let slangFam = NounBankMark.identity(for: word, category: category).family
            let canonFam = NounBankMark.identity(for: canon, category: category).family
            guard slangFam == canonFam else { continue }
            guard isAliasOfCanonical(word, canon) else { continue }
            guard words.contains(where: { norm($0) == norm(canon) }) else { continue }
            if let further = canonical(for: canon, category: category), norm(further) != norm(canon) {
                drop.insert(norm(word))
            } else {
                drop.insert(norm(canon))
            }
        }
        let afterCanon = words.filter { !drop.contains(norm($0)) }
        return collapseSlangStemVariants(
            collapseBareHouseAliases(afterCanon, category: category),
            category: category
        )
    }

    /// Extra house names for the same family (`Louis V` / `LV` / `Vuitton`) collapse to
    /// one chip. Product tiles (`Louis pouch`, `Gucci bag`, `perc 30`) stay.
    private static func collapseBareHouseAliases(_ words: [String], category: NounBankCategory) -> [String] {
        let norm: (String) -> String = { NounBankMark.normalize($0) }
        var groups: [String: [String]] = [:]
        var order: [String] = []
        for word in words {
            guard isBareHouseAlias(word) else { continue }
            guard let canon = canonical(for: word, category: category), isAliasOfCanonical(word, canon) else { continue }
            let key = norm(canon) + "\u{1e}" + NounBankMark.identity(for: word, category: category).family
            if groups[key] == nil {
                order.append(key)
                groups[key] = []
            }
            groups[key, default: []].append(word)
        }
        var drop = Set<String>()
        for key in order {
            let aliases = groups[key] ?? []
            guard aliases.count > 1 else { continue }
            let keep = preferredHouseAlias(aliases, category: category)
            for word in aliases where norm(word) != norm(keep) {
                drop.insert(norm(word))
            }
        }
        return words.filter { !drop.contains(norm($0)) }
    }

    /// `blick`/`blicky`, `choppa`/`chopper`/`choppas` share a stem with each other
    /// even when they do not share one with the real name (`Glock`, `Draco`).
    private static func collapseSlangStemVariants(_ words: [String], category: NounBankCategory) -> [String] {
        let norm: (String) -> String = { NounBankMark.normalize($0) }
        var groups: [String: [String]] = [:]
        var order: [String] = []
        for word in words {
            guard isBareHouseAlias(word) else { continue }
            guard let canon = canonical(for: word, category: category) else { continue }
            let stem = slangStem(word)
            guard stem.count >= 4 else { continue }
            let key = norm(canon) + "\u{1e}" + NounBankMark.identity(for: word, category: category).family + "\u{1e}" + stem
            if groups[key] == nil {
                order.append(key)
                groups[key] = []
            }
            groups[key, default: []].append(word)
        }
        var drop = Set<String>()
        for key in order {
            let aliases = groups[key] ?? []
            guard aliases.count > 1 else { continue }
            let keep = preferredHouseAlias(aliases, category: category)
            for word in aliases where norm(word) != norm(keep) {
                drop.insert(norm(word))
            }
        }
        return words.filter { !drop.contains(norm($0)) }
    }

    private static func slangStem(_ word: String) -> String {
        String(NounBankMark.normalize(word).replacingOccurrences(of: " ", with: "").prefix(4))
    }

