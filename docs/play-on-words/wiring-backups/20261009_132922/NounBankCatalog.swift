/// One tappable noun chip. `insertWord` is what the editor gets; `label` is what the tile shows.
struct NounBankItem: Identifiable, Equatable, Sendable {
    var id: String { insertWord }
    let insertWord: String
    let label: String
    let canonical: String?
    let family: String
    let hex: UInt
    let icon: String
    let sortIndex: Int
}

enum NounBankCatalog {
    /// Chip word, real name, house nicknames, and the person's other names.
    /// Used to count and list catalog bars that mention this noun.
    static func mentionPhrases(for item: NounBankItem, category: NounBankCategory? = nil) -> [String] {
        let key = NounBankMark.normalize(item.insertWord)
        if category == .guns, key == "uzi" {
            return ["the uzi", "a uzi", "an uzi", "my uzi"]
        }
        if let leads = mentionLeads[key] {
            return leads
        }
        var phrases = [item.insertWord]
        if let canonical = item.canonical {
            phrases.append(canonical)
        }
        phrases.append(contentsOf: NounBankMark.familyAliases(for: item.insertWord))
        phrases.append(contentsOf: lyricNamePhrases(for: item))
        if let extra = mentionExtras[key] {
            phrases.append(contentsOf: extra)
        }
        return phrases
    }

    /// Spoken nicknames from the signature list. A one-word piece of a longer
    /// name is not a search phrase when other chips share that word.
    /// "Bruce" on Bruce Lee was pulling Bruce Banner and Bruce Wayne.
    private static func lyricNamePhrases(for item: NounBankItem) -> [String] {
        let names = SignatureCatalog.namePhrases(icon: item.icon, spoken: item.insertWord)
        let chipTokens = NounBankMark.normalize(item.insertWord).split(separator: " ").map(String.init)
        guard chipTokens.count > 1 else { return names }
        return names.filter { name in
            let tokens = NounBankMark.normalize(name).split(separator: " ").map(String.init)
            guard tokens.count == 1, let token = tokens.first else { return true }
            return !ambiguousNameTokens.contains(token)
        }
    }

    /// First or last names that belong to more than one chip.
    private static let ambiguousNameTokens: Set<String> = {
        var names = Set<String>()
        for category in NounBankCategory.allCases {
            for word in NounBankStore.words(for: category) {
                names.insert(NounBankMark.normalize(word))
            }
        }
        var counts: [String: Int] = [:]
        for name in names {
            var seen = Set<String>()
            for token in name.split(separator: " ") where seen.insert(String(token)).inserted {
                counts[String(token), default: 0] += 1
            }
        }
        return Set(counts.compactMap { token, count in count >= 2 ? token : nil })
    }()

    /// Phrases that share this chip's word but name a different person or thing.
    /// Bare "wayne" stays on Lil Wayne. "john wayne" does not.
    static func mentionExclusions(for item: NounBankItem, category: NounBankCategory? = nil) -> [String] {
        let key = NounBankMark.normalize(item.insertWord)
        if category == .artists, key == "uzi" {
            return ["the uzi", "a uzi", "an uzi", "my uzi"]
        }
        return mentionExclusionTable[key] ?? []
    }

    /// The other half of a sound-swap. Both phrases have to be in the same line.
    static func mentionPartners(for item: NounBankItem) -> [String] {
        mentionPartnerTable[NounBankMark.normalize(item.insertWord)] ?? []
    }

